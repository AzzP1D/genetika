export function initiationChoice(step, value) {
  if (!Object.hasOwn(correct, step)) return {};
  if (correct[step] === value) return { next: INITIATION_STEPS[INITIATION_STEPS.indexOf(step) + 1] };
  return { error: errors[step] };
}

export function initiationPose(step, time, cut, index, focus) {
  const position = INITIATION_STEPS.indexOf(step);
  const fraction = (first, last) => Math.min(1, Math.max(0, (time - first) / (last - first)));
  return {
    step, cut, focus,
    origin: step === 'origin' ? fraction(0, 4.6) : 1,
    helper: step === 'scan' ? fraction(0, 1.45) : Number(position > 3),
    delivery: step === 'scan' ? fraction(0.2, 1.75) : Number(position > 3),
    loading: step === 'scan' ? fraction(1.75, 3.15) : Number(position > 3),
    scan: step === 'scan' ? fraction(3.05, 4.8) : Number(position > 3),
    assembly: step === 'assemble' ? fraction(0.25, 3) : Number(position > 6),
    reading: readingState(step, index, time),
  };
}
